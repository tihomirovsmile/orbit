export const languages = ["ru", "uk", "en", "it", "es"] as const;
export type Language = (typeof languages)[number];
export type User = {
  id: string;
  username: string;
  displayName: string;
  bio: string;
  avatar: string | null;
  type: "human" | "ai";
  role: string;
  language: Language;
  country: string;
  status: string;
  lastSeen: number;
  createdAt: number;
  verified: number;
  presence?: { online: boolean; lastSeen: number; visible: boolean };
  presenceVisibility?: string;
  automated?: boolean;
  permissions?: { manageAi?: boolean; createPersonas?: boolean };
  age?: number | null;
  birthDate?: string | null;
  frozen?: boolean;
  deleting?: boolean;
  deletionAt?: number | null;
  state?: string;
  persona?: any;
  memories?: any[];
};
export type Space = {
  membership?: { role: string; muted: number };
  id: string;
  kind: "dm" | "group" | "channel";
  title: string;
  slug: string;
  description: string;
  visibility: string;
  ownerId: string;
  members: number;
  joined: number;
  lastText?: string;
  lastAt?: number;
  unread?: number;
  frozen: number;
  otherUser?: User;
  invite?: string;
  rules?: string;
};
export type Message = {
  id: string;
  spaceId: string;
  senderId: string;
  text: string;
  createdAt: number;
  editedAt: number | null;
  deletedAt: number | null;
  replyTo: string | null;
  forwardedFrom: string | null;
  pinned: number;
  displayName: string;
  type: string;
  avatar: string | null;
  attachments: any[];
  reactions: { emoji: string; count: number; mine: number }[];
  readCount: number;
};
